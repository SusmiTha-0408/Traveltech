def t(key, lang="en", **kwargs):
    """
    Safely retrieves the translated string for a given key and language.
    Falls back to English if the key or language is missing.
    Supports kwargs string formatting.
    """
    if key not in TEXTS:
        return key
    lang_dict = TEXTS[key]
    val = lang_dict.get(lang) or lang_dict.get("en") or key
    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            return val
    return val

def get_translated_city(city_str, lang="en"):
    """
    Translates common city names to selected language if available.
    """
    if not city_str:
        return city_str
    clean = str(city_str).lower()
    for k, v in CITY_TRANSLATIONS.items():
        if k in clean:
            return v.get(lang, v.get("en", city_str))
    return city_str

